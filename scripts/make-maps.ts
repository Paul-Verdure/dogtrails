/**
 * Engraved base maps, night and day -> static/maps/{world,atlantic}-{night,day}.svg
 * Ported from the Claude Design hand-off (make-maps.mjs); visual rules in docs/DESIGN.md §6.
 * Projections live in src/lib/map/projections.ts so MapView places stars with the same ones.
 *
 * Source: Natural Earth (public domain) via the world-atlas npm package (TopoJSON). The source is
 * written into each SVG (<metadata>) for the /sources page.
 *
 * usage: node scripts/make-maps.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoGraticule, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import type { GeometryCollection, Topology } from 'topojson-specification';
import { MAPS, type MapName } from '../src/lib/map/projections.ts';

const OUT = 'static/maps';
const require = createRequire(import.meta.url);
const atlasVersion = (
	JSON.parse(readFileSync(require.resolve('world-atlas/package.json'), 'utf8')) as { version: string }
).version;

// Build-time colours of the engraved SVGs (not CSS: the files are static images).
// Night/day values match the --dt-* tokens' intent; see docs/DESIGN.md §6.
const PALETTE = {
	night: { hatch: '#3B5274', grat: '#24395A', ripple: '#7FA0C8', land: '#15223A', coast: '#8DA6C6', coastOpacity: 0.75, sphere: '#3B5274' },
	day: { hatch: '#9AA8BC', grat: '#CDBFA6', ripple: '#5F7598', land: '#ECE3D2', coast: '#33435E', coastOpacity: 0.9, sphere: '#8A94A6' }
} as const;
type Mode = keyof typeof PALETTE;

function engrave(name: MapName, mode: Mode) {
	const p = MAPS[name];
	const c = PALETTE[mode];
	const topo = JSON.parse(readFileSync(require.resolve(`world-atlas/${p.atlas}`), 'utf8')) as Topology<{
		land: GeometryCollection;
	}>;
	const land = feature(topo, topo.objects.land);
	const path = geoPath(p.make()).digits(1);
	const L = path(land) ?? '';
	const S = p.sphere ? path({ type: 'Sphere' }) : null;
	const ripples = (
		[
			[18, 0.05],
			[12, 0.08],
			[7, 0.12]
		] as const
	)
		.map(([w, o]) => `<use href="#land" fill="none" stroke="${c.ripple}" stroke-opacity="${o}" stroke-width="${w}" stroke-linejoin="round"/>`)
		.join('');
	const body = `
<path d="${path(geoGraticule().step([p.step, p.step])())}" fill="none" stroke="${c.grat}" stroke-width="0.5" stroke-dasharray="1 3"/>
${ripples}
<use href="#land" fill="${c.land}"/>
<use href="#land" fill="url(#hatch)"/>
<use href="#land" fill="none" stroke="${c.coast}" stroke-width="0.7" stroke-opacity="${c.coastOpacity}"/>`;
	const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${p.W} ${p.H}">
<metadata>Land: Natural Earth (public domain, naturalearthdata.com) via world-atlas@${atlasVersion} ${p.atlas}. Generated by scripts/make-maps.ts.</metadata>
<defs>
<path id="land" d="${L}"/>
<pattern id="hatch" width="3.2" height="3.2" patternUnits="userSpaceOnUse" patternTransform="rotate(35)"><line x1="0" y1="0" x2="0" y2="3.2" stroke="${c.hatch}" stroke-width="0.85"/></pattern>
${S ? `<clipPath id="sph"><path d="${S}"/></clipPath>` : ''}
</defs>
${S ? `<g clip-path="url(#sph)">${body}</g><path d="${S}" fill="none" stroke="${c.sphere}" stroke-width="1"/>` : body}
</svg>
`;
	const file = `${OUT}/${name}-${mode}.svg`;
	writeFileSync(file, svg);
	console.log(file, `${(svg.length / 1024).toFixed(0)} KB`);
}

mkdirSync(OUT, { recursive: true });
for (const name of Object.keys(MAPS) as MapName[]) for (const mode of Object.keys(PALETTE) as Mode[]) engrave(name, mode);
